#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
/**
 * Emit `packages/ref-id/test/surface.generated.ts` from `spec.openRPC`: a file `tsc` checks, so that a
 * mismatch between the TypeScript entry point's real function/type signatures and what openRPC declares
 * is a compile error rather than something only a runtime test happens to exercise.
 *
 * For each method it emits one line assigning the function imported **from the entry point**
 * (`../src/index.ts`) to the type the method's `params`/`result` declare, per the schema-to-TypeScript
 * mapping in `packages/ref-id/AGENTS.md`'s sibling brief (see the module doc below for the exact rules).
 * For each named, non-primitive schema under `openRPC.components.schemas` it emits a type-level
 * assertion that a type of that name is exported. Reads the specification only — nothing here restates
 * a table `spec/ref-id.json` already declares (the repo guardrail this script must not violate).
 *
 * `--check` regenerates the file in memory and diffs it against what's committed, exiting non-zero (and
 * printing nothing to stdout, the diff to stderr) when they differ — the guard `npm test` runs so a
 * stale generated file fails the suite instead of quietly drifting from the spec.
 *
 *   node scripts/gen-surface-ts.mjs           # (re)write the file
 *   node scripts/gen-surface-ts.mjs --check   # fail if the committed file is stale
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

const ROOT = fileURLToPath(new URL("..", import.meta.url))
const OUT_PATH = `${ROOT}packages/ref-id/test/surface.generated.ts`
const ENTRY = "../src/index.ts"

const spec = JSON.parse(readFileSync(`${ROOT}spec/ref-id.json`, "utf8"))
const doc = spec.openRPC
const schemas = doc.components.schemas

// Schemas the mapping resolves to a bare TypeScript primitive/union rather than to "the exported type
// of that name" — Identifier is deliberately just `string` in this port (no branded alias exists, and
// none is expected), so it gets no separate existence assertion. IdentifierOrParsed, by contrast, *is*
// checked for existence below even though a signature substitutes its expansion — see the openRPC brief.
const NO_EXISTENCE_CHECK = new Set(["Identifier"])
// Composition-only schemas: ParseResult is assembled from these via `allOf`, but neither is a value type
// a language is expected to export under its own name.
const COMPOSITION_ONLY = new Set(["ParseFields", "ParseInvariants"])

function schemaName(ref) {
  const match = /^#\/components\/schemas\/(.+)$/.exec(ref ?? "")
  if (!match) throw new Error(`not a components/schemas $ref: ${JSON.stringify(ref)}`)
  return match[1]
}

/** Top-level schema → TypeScript type text, per the mapping rules the brief pins down. */
function tsType(schema) {
  if (schema.$ref) {
    const name = schemaName(schema.$ref)
    if (name === "Identifier") return "string"
    if (name === "IdentifierOrParsed") return "string | ParseResult"
    return name
  }
  if (schema.oneOf) {
    return schema.oneOf.map((branch) => tsType(branch)).join(" | ")
  }
  if (schema.type === "null") return "null"
  if (schema.type === "boolean") return "boolean"
  if (schema.type === "string") return "string"
  if (schema.type === "array") return `readonly ${tsType(schema.items)}[]`
  // A truly empty `{}` schema ("any JSON") maps to `unknown`, per the brief's rule. Every other shape
  // (including a bare `{ "type": "object" }`) is now named via `$ref` (loadSpec/loadSpecFrom → Spec), so
  // there is no other user of a bare object mapping left — an unmapped schema throws instead of guessing.
  if (!schema.type && Object.keys(schema).length === 0) return "unknown"
  throw new Error(`gen-surface-ts.mjs does not know how to map schema ${JSON.stringify(schema)}`)
}

function paramType(method) {
  return (method.params ?? []).map((param) => tsType(param.schema))
}

function resultType(method) {
  return tsType(method.result.schema)
}

const lines = []
lines.push("// SPDX-License-Identifier: Apache-2.0")
lines.push("//")
lines.push("// AUTO-GENERATED by scripts/gen-surface-ts.mjs from spec.openRPC — do not edit by hand.")
lines.push("// Regenerate: `node scripts/gen-surface-ts.mjs`. Checked stale by `npm test` (`--check`) and")
lines.push("// checked for real by `npm run typecheck`, which is the actual assertion this file exists for:")
lines.push("// each line below only compiles when the entry point's exported name has the type openRPC")
lines.push("// declares for it, or is missing/misnamed entirely, which is exactly what a divergence is.")
lines.push("")

const functionImports = doc.methods.map((method) => method.name).sort()
const namedSchemas = Object.keys(schemas).filter((name) => !NO_EXISTENCE_CHECK.has(name) && !COMPOSITION_ONLY.has(name))
// Type names used in signatures (deduped) plus every named schema checked for existence — imported once.
const signatureTypeNames = new Set()
for (const method of doc.methods) {
  for (const param of method.params ?? []) collectTypeNames(param.schema, signatureTypeNames)
  collectTypeNames(method.result.schema, signatureTypeNames)
}
function collectTypeNames(schema, into) {
  if (schema.$ref) {
    const name = schemaName(schema.$ref)
    if (name !== "Identifier" && name !== "IdentifierOrParsed") into.add(name)
    return
  }
  if (schema.oneOf) for (const branch of schema.oneOf) collectTypeNames(branch, into)
  if (schema.type === "array" && schema.items) collectTypeNames(schema.items, into)
}
const typeImports = Array.from(new Set([...signatureTypeNames, ...namedSchemas])).sort()

// The error hierarchy: `x-error-type` names the base class every declared error kind extends, and
// `components.errors` names the kinds themselves — `Build` → the exported class `BuildError`, etc. Both
// the base and each `<Kind>Error` are classes, so they are real (value) imports, not `import type`: a
// `typeof` on a type-only binding is refused by `verbatimModuleSyntax`.
const errorBaseName = doc["x-error-type"]
const errorClassNames = Object.keys(doc.components.errors)
  .map((kind) => `${kind}Error`)
  .sort()

lines.push(`import { ${[...functionImports, errorBaseName, ...errorClassNames].sort().join(", ")} } from "${ENTRY}"`)
lines.push(`import type { ${typeImports.join(", ")} } from "${ENTRY}"`)
lines.push("")
lines.push("// --- one assignment per openRPC method: the imported function against its declared signature ---")
lines.push("")
for (const method of doc.methods) {
  const params = paramType(method)
  const result = resultType(method)
  const signature = `(${params.map((type, index) => `${(method.params ?? [])[index].name}: ${type}`).join(", ")}) => ${result}`
  lines.push(`const _${method.name}: ${signature} = ${method.name}`)
}
lines.push("")
lines.push("// --- one type-level assertion per named value type: the exported type exists under this name ---")
lines.push("")
for (const name of namedSchemas) {
  lines.push(`type _${name} = ${name}`)
}
lines.push("")
lines.push(`// --- error hierarchy: every declared error kind's class extends ${errorBaseName} ---`)
lines.push("")
for (const className of errorClassNames) {
  lines.push(`declare const _instance_${className}: InstanceType<typeof ${className}>`)
  lines.push(`const _isRefIdError_${className}: ${errorBaseName} = _instance_${className}`)
}
lines.push("")
lines.push("export {}")
lines.push("")

const generated = lines.join("\n")

if (process.argv.includes("--check")) {
  let committed
  try {
    committed = readFileSync(OUT_PATH, "utf8")
  } catch {
    committed = null
  }
  if (committed !== generated) {
    console.error(`${OUT_PATH} is stale against spec.openRPC — run: node scripts/gen-surface-ts.mjs`)
    process.exit(1)
  }
  console.log(`gen-surface-ts: ${OUT_PATH} is current`)
} else {
  writeFileSync(OUT_PATH, generated)
  console.log(`gen-surface-ts: wrote ${OUT_PATH}`)
}
