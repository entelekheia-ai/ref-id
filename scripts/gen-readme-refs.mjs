#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
/**
 * Write each port's own `ref:` identifier into the README, between the `ref-ids` markers.
 *
 * One identifier per registry the ports ship through, each carrying the release and — as the declared name
 * inside it — the specification that release embeds: `ref:pkg:npm/@entelekheia/ref-id@0.5.0#spec@1.4.0`.
 * The pair is what a consumer needs and what the package version alone never told it: 0.3.0 and 0.4.0 both
 * embedded a document calling itself 1.3.0 with different type registries.
 *
 * The identifiers are minted by this package's own `build`, so a shape the scheme refuses fails here rather
 * than reaching the README. Runs inside `npm run version`, so the "Version Packages" pull request carries the
 * new lines; `--check` regenerates into memory and fails on any difference, and the release workflow's gates
 * run it. Both do nothing while a changeset is pending (see below).
 *
 *   node scripts/gen-readme-refs.mjs [--check]
 */
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const README = join(ROOT, "README.md")
const START = "<!-- ref-ids:start — generated by scripts/gen-readme-refs.mjs, do not edit by hand -->"
const END = "<!-- ref-ids:end -->"
const checkOnly = process.argv.includes("--check")

// Between two releases the specification on main is ahead of the package version, so the pair this script
// would write names a release that never existed (0.4.0 with spec 1.4.0, when 0.4.0 embedded 1.3.0). The
// block is written by `npm run version`, after `changeset version` has consumed every pending changeset, and
// checked only when none is pending — which is exactly a release commit.
const pending = readdirSync(join(ROOT, ".changeset")).filter((name) => name.endsWith(".md") && name !== "README.md")
if (pending.length > 0) {
  console.log(`README.md ref-ids: ${pending.length} changeset(s) pending, left for \`npm run version\` to write`)
  process.exit(0)
}

// The Node entry reads the specification from the package's own copy, which `prebuild`/`pretest` make; make
// it here too, so a spec edited since the last build is the one the identifiers are checked against.
const packageSpec = join(ROOT, "packages/ref-id/spec")
mkdirSync(packageSpec, { recursive: true })
for (const file of ["ref-id.json", "ref-id.json.sha256"]) {
  copyFileSync(join(ROOT, "spec", file), join(packageSpec, file))
}
const { build } = await import(join(ROOT, "packages/ref-id/src/index.ts"))

const version = JSON.parse(readFileSync(join(ROOT, "packages/ref-id/package.json"), "utf8")).version
const specVersion = JSON.parse(readFileSync(join(ROOT, "spec/ref-id.json"), "utf8")).specVersion
const fragment = `spec@${specVersion}`

const ports = [
  ["`@entelekheia/ref-id` (npm)", `npm/@entelekheia/ref-id@${version}`],
  ["`ref-id` (crates.io)", `cargo/ref-id@${version}`],
  ["`RefId` (Swift Package Manager)", `swift/github.com/entelekheia-ai/ref-id@${version}`],
]
const rows = ports.map(([name, locator]) => `| ${name} | \`${build({ type: "pkg", locator, fragment })}\` |`)

const block = [
  START,
  "",
  `Every port of this release, named in the scheme it implements. The fragment is the specification the release`,
  `embeds: pin \`specVersion\` through it rather than through the package version.`,
  "",
  "| Port | Identifier |",
  "|---|---|",
  ...rows,
  "",
  END,
].join("\n")

const readme = readFileSync(README, "utf8")
const from = readme.indexOf(START)
const to = readme.indexOf(END)
if (from === -1 || to === -1 || to < from) {
  console.error(`README.md has no ${START} … ${END} block to fill`)
  process.exit(1)
}
const next = readme.slice(0, from) + block + readme.slice(to + END.length)

if (checkOnly) {
  if (next !== readme) {
    console.error("README.md's ref-ids block is stale — run `node scripts/gen-readme-refs.mjs`")
    process.exit(1)
  }
  console.log(`README.md ref-ids are current: ${version}, spec ${specVersion}`)
} else {
  writeFileSync(README, next)
  console.log(`README.md ref-ids -> ${version}, spec ${specVersion}`)
}
